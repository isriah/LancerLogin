// Maintainer-only: execute trusted local migrations on an empty local database.
import { DatabaseSync } from 'node:sqlite';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { unstable_splitSqlQuery } from 'wrangler';
const digest = value => createHash('sha256').update(value).digest('hex');
const args = process.argv.slice(2);
if (args.length && (args.length !== 2 || args[0] !== '--schema' || !['46', '47', '48', '49'].includes(args[1]))) throw Error('catalog-schema-argument');
const target = args.length ? Number(args[1]) : 49;
const suffix = target === 49 ? '' : `-${target}`;
const directory = new URL('../apps/api/migrations/', import.meta.url);
const names = readdirSync(directory).filter(name => /^\d{4}_.+\.sql$/.test(name)).sort().slice(0, target);
if (names.length !== target || names.some((name, i) => Number(name.slice(0, 4)) !== i + 1)) throw Error('catalog-migration-prefix');
const db = new DatabaseSync(':memory:'), ledger = [];
try {
  for (const id of names) { const bytes = readFileSync(new URL(id, directory)); ledger.push({ id, sha256: digest(bytes) }); for (const sql of unstable_splitSqlQuery(bytes.toString())) db.exec(sql); }
  // Wrangler 4.127.1 getCreateMigrationsTableQuery; native metadata is explicit.
  db.exec('CREATE TABLE IF NOT EXISTS "d1_migrations"(\n\t\tid         INTEGER PRIMARY KEY AUTOINCREMENT,\n\t\tname       TEXT UNIQUE,\n\t\tapplied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL\n\t);');
  const objects = db.prepare("SELECT type,name,tbl_name,sql FROM sqlite_schema WHERE name NOT GLOB 'sqlite_*' OR type='index' OR name='sqlite_sequence' ORDER BY type,name").all();
  const tables = objects.filter(object => object.type === 'table').map(object => {
    const columns = db.prepare(`PRAGMA table_xinfo("${object.name}")`).all();
    if (columns.some(column => column.hidden || ['rowid', '_rowid_', 'oid'].includes(column.name.toLowerCase())) || /WITHOUT\s+ROWID|VIRTUAL\s+TABLE/i.test(object.sql)) throw Error('unsupported-catalog-table');
    return { name: object.name, columns: columns.map(column => column.name) };
  });
  const value = { format: 1, schema: target, ledger, chainSha256: digest(JSON.stringify(ledger)), objects, tables };
  const canonical = JSON.stringify(value);
  writeFileSync(new URL(`../apps/updater/src/snapshot-catalog${suffix}.mjs`, import.meta.url), `// Generated by scripts/generate-snapshot-catalog.mjs from trusted migrations.\nexport const catalogSha256 = '${digest(canonical)}';\nexport const snapshotCatalog = ${canonical};\n`);
} finally { db.close(); }
